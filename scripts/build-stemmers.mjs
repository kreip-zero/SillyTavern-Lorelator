// Bundles the snowball-stemmers npm package (UMD) into an ES module the browser can import.
import { build } from 'esbuild';

await build({
    stdin: {
        contents: "export { newStemmer, algorithms } from 'snowball-stemmers';",
        resolveDir: process.cwd(),
    },
    bundle: true,
    format: 'esm',
    minify: true,
    outfile: 'lib/snowball.js',
    banner: { js: '// Generated by scripts/build-stemmers.mjs from snowball-stemmers (MIT). Do not edit.' },
});

const { algorithms } = await import('../lib/snowball.js');
console.log(algorithms().join(', '));
